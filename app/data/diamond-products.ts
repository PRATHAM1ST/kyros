export function getDiamondProductByHandle(
  handle: string,
): DiamondProduct | undefined {
  return DIAMOND_PRODUCTS.find((p) => p.handle === handle);
}

export function getAllDiamondShapes(): {
  shape: DiamondProduct['diamond']['shape'];
  count: number;
}[] {
  const map = new Map<DiamondProduct['diamond']['shape'], number>();
  for (const p of DIAMOND_PRODUCTS) {
    const s = p.diamond.shape;
    map.set(s, (map.get(s) || 0) + 1);
  }
  return Array.from(map.entries()).map(([shape, count]) => ({shape, count}));
}
